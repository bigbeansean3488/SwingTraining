// Regenerates tests/fixtures/*.json from the synthetic pose model.
// Run: node scripts/make-fixtures.ts   (Node >= 23.6 strips TypeScript types)
import { mkdirSync, writeFileSync } from 'node:fs';
import {
  generateBatting,
  generatePitching,
  type SynthOptions,
  type SynthSequence,
} from '../tests/synthetic.ts';

function compact(seq: SynthSequence, params: SynthOptions & { kind: string }) {
  return {
    note: 'Synthetic keypoints generated by scripts/make-fixtures.ts. Not a real person.',
    params,
    width: seq.width,
    height: seq.height,
    frames: seq.frames.map((f) => [f.t, f.lm ? f.lm.flatMap((p) => [p.x, p.y, p.v]) : null]),
  };
}

const out = 'tests/fixtures';
mkdirSync(out, { recursive: true });
const sets: [string, 'batting' | 'pitching', SynthOptions][] = [
  ['batting-240fps', 'batting', { fps: 240 }],
  ['batting-120fps-noisy', 'batting', { fps: 120, noisePx: 2, seed: 3 }],
  ['batting-30fps', 'batting', { fps: 30 }],
  ['batting-lefty-240fps-noisy', 'batting', { fps: 240, forward: -1, noisePx: 2, seed: 5 }],
  ['pitching-240fps', 'pitching', { fps: 240 }],
  ['pitching-lefty-120fps-noisy', 'pitching', { fps: 120, forward: -1, noisePx: 2, seed: 9 }],
  ['pitching-30fps', 'pitching', { fps: 30 }],
];
for (const [name, kind, opts] of sets) {
  const seq = kind === 'batting' ? generateBatting(opts) : generatePitching(opts);
  writeFileSync(`${out}/${name}.json`, JSON.stringify(compact(seq, { kind, ...opts })));
  console.log(`${name}: ${seq.frames.length} frames`);
}
